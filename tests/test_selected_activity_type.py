import pytest

from calendar_pedagoga.lesson_content import refine_selected_activity_type


@pytest.mark.parametrize("source,result,expected", [
    ("Развлечения, школьные праздники", "Выполняет практическое задание по теме школы.", "праздник"),
    ("Рисунки", "Выполняет рисунки.", "творческое занятие"),
    ("Анализ ситуаций", "Анализирует ситуации.", "ситуационное занятие"),
    ("Применение приемов самомассажа", "Выполняет приемы самомассажа.", "практикум по самомассажу"),
    ("Проведение ролевых игр", "Участвует в ролевых играх.", "ролевое игровое занятие"),
    ("Проведение дидактических игр", "Участвует в дидактических играх.", "дидактическое занятие"),
    ("Животные в рисунках детей", "Выполняет практическое задание по теме.", "творческое занятие"),
    ("Неуточнённое содержание", "Выполняет практическое задание по теме.", "практикум"),
    ("Лыжные прогулки. Походы выходного дня", "Совершает прогулки, участвует в походах.", "комбинированное занятие"),
])
def test_selected_source_type(source, result, expected):
    assert refine_selected_activity_type("практикум", source, result) == expected


@pytest.mark.parametrize("candidate", [
    "практикум по работе со снаряжением", "измерительный практикум",
    "краеведческий практикум", "учебно-тренировочное занятие",
    "практикум по страховке", "туристские соревнования",
])
def test_preserve_grounded_specific_types(candidate):
    assert refine_selected_activity_type(candidate, "Отработка действий", "Отрабатывает действия.") == candidate


def test_didactic_label_requires_didactic_source():
    assert refine_selected_activity_type(
        "дидактическое занятие", "Развлечения, школьные праздники",
        "Выполняет практическое задание по теме.",
    ) == "праздник"


@pytest.mark.parametrize("source", [
    "Обсуждение школьных праздников",
    "Обсуждение правил игры",
    "Сравнение рисунков",
])
def test_discussing_a_form_is_not_performing_it(source):
    assert refine_selected_activity_type(
        "практическое занятие", source,
        "Выполняет практическое задание по теме.",
    ) == "практическое занятие"
